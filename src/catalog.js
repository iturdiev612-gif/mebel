export function normalizePhone(value, country) {
  let digits = value.replace(/\D/g, '');
  const code = country.prefix.slice(1);
  if (digits.startsWith(code) && (value.trim().startsWith(country.prefix) || digits.length === country.digits + code.length)) digits = digits.slice(code.length);
  return digits.slice(0, country.digits);
}
